#!/usr/bin/env python3
"""Generate CONFORMANCE.md from the vendored CAMARA test definitions.

Every scenario defaults to ✅ (behaviour implemented and the expected status/code produced).
Exceptions are listed explicitly in RULES below, each with a reason, so the classification is
reviewable. Regression tests for the reviewed gaps: tests/test_conformance.py (+ per-API tests).

  python3 tools/conformance_report.py > CONFORMANCE.md
"""
from __future__ import annotations

import collections
import glob
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from parse_features import parse  # noqa: E402

OK, PARTIAL, NO, NA = "✅", "⚠️", "⛔", "➖"

# (predicate on scenario dict, mark, note) — first match wins
RULES = [
    (lambda s: s["status"] == 429 or "QUOTA_EXCEEDED" in s["codes"] or "TOO_MANY_REQUESTS" in s["codes"],
     OK, "Per-client limiter: rate_limit.per_minute → TOO_MANY_REQUESTS, rate_limit.daily_quota → QUOTA_EXCEEDED."),
    (lambda s: "PRIVATE_KEY_JWT" in s["title"] and s["status"] in (200, 201),
     PARTIAL, "PRIVATE_KEY_JWT sink credentials aren't supported; creation returns 422 PRIVATE_KEY_JWT_NOT_CONFIGURED."),
    (lambda s: "async" in s["title"].lower() and s["status"] == 202,
     NA, "Subscriptions are created synchronously (201); async 202 creation is optional."),
    (lambda s: s["status"] == 202 and ("Delete" in s["title"] or "deletion" in s["title"]),
     OK, "Delete returns 204 (the spec allows 202 or 204)."),
    (lambda s: "activation date" in s["title"] or "first time that the SIM is installed" in s["title"],
     PARTIAL, "No SIM activation / first-install history in Open5GS: returns null + monitoredPeriod."),
    (lambda s: "never been associated with a sim" in s["title"],
     PARTIAL, "Unknown numbers return 404 IDENTIFIER_NOT_FOUND rather than a 200 with null."),
    (lambda s: "local regulations" in s["title"],
     PARTIAL, "null + monitoredPeriod is returned only when no swap was recorded (no privacy-policy mode)."),
    (lambda s: "restricted to certain devices" in s["title"] or "no QoS profiles associated" in s["title"],
     PARTIAL, "All lab QoS profiles are available to every device; no per-device restriction."),
    (lambda s: "additional KPIs" in s["title"],
     PARTIAL, "Only additionalKPIs.connectivityType (\"5G\"); no signalStrength from the lab RAN."),
    (lambda s: s["spec"].startswith("ConnectivityInsights") and "meet" in s["title"],
     OK, "ICMP-based delay/jitter/loss; throughput only with iperf3 enabled (otherwise omitted)."),
    (lambda s: "3-legged" in s["title"] or "three-legged" in s["title"],
     OK, "3-legged tokens come from the network-based /oauth2/authorize flow."),
    (lambda s: s["spec"].startswith("NumberVerification"),
     OK, "Network-based auth over the UE data path; single-use, <= 300 s tokens."),
]


def classify(s: dict) -> tuple[str, str]:
    for pred, mark, note in RULES:
        if pred(s):
            return mark, note
    return OK, ""


def main() -> None:
    root = os.path.join(os.path.dirname(__file__), "..")
    files = sorted(glob.glob(os.path.join(root, "specs", "*", "test_definitions", "*.feature")))
    rows = []
    for f in files:
        rel = os.path.relpath(f, root)
        for s in parse(rel):
            mark, note = classify(s)
            rows.append({**s, "mark": mark, "note": note})

    by_spec = collections.OrderedDict()
    for r in rows:
        by_spec.setdefault(r["spec"], []).append(r)

    out = []
    w = out.append
    w("# CAMARA conformance — open5gs-camara lab gateway\n")
    w("Generated by `tools/conformance_report.py` from the vendored test definitions "
      "(`specs/<Repo>@<tag>/test_definitions/*.feature`).\n")
    w(f"{OK} supported · {PARTIAL} partial (see note) · {NO} not supported · {NA} not applicable\n")
    w("This is a reviewed mapping, not an automated run of the Gherkin steps. The expected status and error code of "
      "every scenario were checked against the implementation. Gaps found in that review were fixed and are "
      "covered by `tests/test_conformance.py` and the per-API tests (`pytest`).\n")
    w("## Summary\n")
    w("| API (repo@tag) | Scenarios | ✅ | ⚠️ | ⛔ | ➖ |")
    w("|---|---:|---:|---:|---:|---:|")
    tot = collections.Counter()
    for spec, rs in by_spec.items():
        c = collections.Counter(r["mark"] for r in rs)
        tot.update(c)
        w(f"| {spec} | {len(rs)} | {c[OK]} | {c[PARTIAL]} | {c[NO]} | {c[NA]} |")
    w(f"| **Total** | **{len(rows)}** | **{tot[OK]}** | **{tot[PARTIAL]}** | **{tot[NO]}** | **{tot[NA]}** |\n")
    w("## Lab-wide deviations\n")
    w("- **Sinks:** CAMARA requires `https` sinks; the lab accepts `http` (`notify.allow_http_sink`).")
    w("- **Roaming:** UERANSIM can't roam; roaming scenarios use the lab override for the visited PLMN.")
    w("- **QoD radio leg:** UERANSIM's gNB drops N2 on `PDUSessionResourceModifyRequest`; the QoS flow is verified "
      "in the core (SMF/PCF), not on the radio.")
    w("- **Swap history:** starts when the gateway starts monitoring (no historic SIM/device data in Open5GS).")
    w("- **QoD duration out of range:** returns `INVALID_ARGUMENT` per the r4.3 test definitions "
      "(the OpenAPI also lists `QUALITY_ON_DEMAND.DURATION_OUT_OF_RANGE`).\n")
    for spec, rs in by_spec.items():
        w(f"## {spec}\n")
        w("| | Scenario | Expected | Note |")
        w("|---|---|---|---|")
        for r in rs:
            exp = f"{r['status'] or 'event'} {' / '.join(r['codes'])}".strip()
            title = r["title"].replace("|", "\\|")
            w(f"| {r['mark']} | `{r['tag']}` {title} | {exp} | {r['note']} |")
        w("")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
